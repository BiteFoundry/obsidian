<#
.SYNOPSIS
    Installs the `bitefoundry-obsidian` terminal launcher on Windows.

.DESCRIPTION
    1. Ensures <RepoRoot>\target\release\bitefoundry-obsidian.exe exists (downloads the prebuilt
       release binary from GitHub `BiteFoundry/obsidian` via `gh` when missing, so
       Rust/Cargo is NOT required on target PCs).
    2. Registers `bitefoundry-obsidian` in the managed launcher block in the PowerShell profile.
    3. If $HOME\Tools\bin exists, adds `bitefoundry-obsidian.cmd` and removes shims generated by the old installer.

.EXAMPLE
    pwsh -File .\scripts\install-profile.ps1
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$ProfilePath = $PROFILE,
    [string]$RepoRoot = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($ProfilePath)) {
    throw 'ProfilePath is empty. Pass -ProfilePath explicitly or run inside a PowerShell host where $PROFILE is defined.'
}

$resolvedRoot = if (Test-Path -LiteralPath $RepoRoot) {
    (Resolve-Path -LiteralPath $RepoRoot).Path
} else {
    $RepoRoot
}

$releaseDir = Join-Path $resolvedRoot 'target\release'
$releaseExe = Join-Path $releaseDir 'bitefoundry-obsidian.exe'

if (-not (Test-Path -LiteralPath $releaseExe)) {
    $gh = Get-Command gh -ErrorAction SilentlyContinue
    if ($gh) {
        Write-Output "[bitefoundry-obsidian] Downloading the standalone executable from GitHub Releases..."
        New-Item -ItemType Directory -Force -Path $releaseDir | Out-Null
        & $gh.Source release download -R 'BiteFoundry/obsidian' --pattern 'bitefoundry-obsidian.exe' --dir $releaseDir --clobber
    }
}

$escapedRoot = $resolvedRoot.Replace("'", "''")
$startMarker = '# >>> obsidian launcher >>>'
$endMarker = '# <<< obsidian launcher <<<'

$block = @"
$startMarker
# Opens the Obsidian terminal client (CLI/TUI/HTTP/MCP) from anywhere.
function bitefoundry-obsidian {
    `$root = '$escapedRoot'
    `$exe = Join-Path `$root 'target\release\bitefoundry-obsidian.exe'
    if (-not (Test-Path -LiteralPath `$exe)) {
        if (Get-Command gh -ErrorAction SilentlyContinue) {
            `$relDir = Split-Path -Parent `$exe
            New-Item -ItemType Directory -Force -Path `$relDir | Out-Null
            gh release download -R 'BiteFoundry/obsidian' --pattern 'bitefoundry-obsidian.exe' --dir `$relDir --clobber 2>`$null
        }
    }
    if (-not (Test-Path -LiteralPath `$exe)) {
        cargo build --release --manifest-path (Join-Path `$root 'Cargo.toml')
        if (`$LASTEXITCODE -ne 0) { return }
    }
    & `$exe @args
}
$endMarker
"@.TrimEnd("`r", "`n")

$parentDir = Split-Path -Parent $ProfilePath
if ($parentDir -and -not (Test-Path -LiteralPath $parentDir)) {
    if ($PSCmdlet.ShouldProcess($parentDir, 'Create PowerShell profile parent directory')) {
        New-Item -ItemType Directory -Force -Path $parentDir | Out-Null
    }
}

$existing = ''
if (Test-Path -LiteralPath $ProfilePath) {
    $existing = Get-Content -LiteralPath $ProfilePath -Raw -Encoding UTF8
    if ($null -eq $existing) { $existing = '' }
}

$pattern = '(?ms)^# >>> obsidian launcher >>>\r?\n.*?^# <<< obsidian launcher <<<\r?\n?'
if ([regex]::IsMatch($existing, $pattern)) {
    $updated = [regex]::Replace($existing, $pattern, { param($m) $block + [Environment]::NewLine }, 1)
    $action = 'Update obsidian launcher block'
} elseif ([string]::IsNullOrWhiteSpace($existing)) {
    $updated = $block + [Environment]::NewLine
    $action = 'Create profile with obsidian launcher block'
} else {
    $trimmed = $existing.TrimEnd("`r", "`n")
    $nl = [Environment]::NewLine
    $updated = $trimmed + $nl + $nl + $block + $nl
    $action = 'Append obsidian launcher block'
}

if ($updated -ne $existing) {
    if ($PSCmdlet.ShouldProcess($ProfilePath, $action)) {
        $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
        [System.IO.File]::WriteAllText($ProfilePath, $updated, $utf8NoBom)
        Write-Output "$action in $ProfilePath."
    }
} else {
    Write-Output "obsidian launcher in $ProfilePath is already up to date."
}

$toolsBin = Join-Path $HOME 'Tools\bin'
if (Test-Path -LiteralPath $toolsBin) {
    $shimPath = Join-Path $toolsBin 'bitefoundry-obsidian.cmd'
    $shimContent = "@echo off`r`nchcp 65001 >nul`r`n`"$releaseExe`" %*`r`n"
    if (!(Test-Path -LiteralPath $shimPath) -and $PSCmdlet.ShouldProcess($shimPath, 'Write PATH shim')) {
        [System.IO.File]::WriteAllText($shimPath, $shimContent, [System.Text.Encoding]::ASCII)
    }

    $oldExe = Join-Path $releaseDir 'obsidian.exe'
    $oldContent = "@echo off`r`nchcp 65001 >nul`r`n`"$oldExe`" %*`r`n"
    foreach ($name in @('obsidian.cmd', 'obs.cmd')) {
        $oldShim = Get-Item -LiteralPath (Join-Path $toolsBin $name) -ErrorAction SilentlyContinue
        if ($oldShim -and !$oldShim.PSIsContainer -and
            !($oldShim.Attributes -band [IO.FileAttributes]::ReparsePoint) -and
            [IO.File]::ReadAllText($oldShim.FullName) -ceq $oldContent -and
            $PSCmdlet.ShouldProcess($oldShim.FullName, 'Remove old Obsidian PATH shim')) {
            Remove-Item -LiteralPath $oldShim.FullName
        }
    }
}
